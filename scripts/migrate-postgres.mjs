import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { DatabaseSync, backup } from 'node:sqlite'
import { Readable, Writable } from 'node:stream'
import { pipeline } from 'node:stream/promises'
import { from as copyFrom, to as copyTo } from 'pg-copy-streams'
import { createPostgresPool, postgresSql } from '../server/postgres.mjs'

const quote = value => '"' + value.replaceAll('"', '""') + '"'
const cell = value => value == null ? '\\N' : '"' + String(value).replaceAll('"', '""') + '"'

export async function copyTable(client, source, table, schema) {
  const columns = source.prepare(`PRAGMA table_info(${quote(table)})`).all()
  const names = columns.map(c => quote(c.name.toLowerCase())).join(', ')
  const primary = columns.filter(c => c.pk).sort((a, b) => a.pk - b.pk)
  if (!primary.length) throw new Error(`Table ${table} requires a primary key for validation`)
  const order = primary.map(c => `${quote(c.name)}${c.type.toUpperCase() === 'TEXT' ? ' COLLATE BINARY' : ''}`).join(', ')
  const targetOrder = primary.map(c => `${quote(c.name.toLowerCase())}${c.type.toUpperCase() === 'TEXT' ? ' COLLATE "C"' : ''}`).join(', ')
  const hash = createHash('sha256')
  let count = 0
  function* rows() {
    for (const row of source.prepare(`SELECT * FROM ${quote(table)} ORDER BY ${order}`).iterate()) {
      const line = columns.map(c => cell(row[c.name])).join(',') + '\n'
      hash.update(line); count++
      yield line
    }
  }
  await pipeline(Readable.from(rows()), client.query(copyFrom(
    `COPY ${quote(schema)}.${quote(table)} (${names}) FROM STDIN WITH (FORMAT csv, NULL '\\N')`)))
  const expected = hash.digest('hex'), received = createHash('sha256')
  await pipeline(client.query(copyTo(
    `COPY (SELECT ${names} FROM ${quote(schema)}.${quote(table)} ORDER BY ${targetOrder}) TO STDOUT WITH (FORMAT csv, NULL '\\N', FORCE_QUOTE *)`)),
  new Writable({ write(chunk, encoding, callback) { received.update(chunk); callback() } }))
  if (received.digest('hex') !== expected) throw new Error(`Content checksum mismatch: ${schema}.${table}`)
  const total = Number((await client.query(`SELECT count(*) AS total FROM ${quote(schema)}.${quote(table)}`)).rows[0].total)
  if (count !== total) throw new Error(`Row count mismatch: ${schema}.${table}`)
  return { table, rows: count, sha256: expected }
}

export async function importDatabase(client, file, schema, { replace = false, snapshotDir } = {}) {
  if (!/^[a-z][a-z0-9_]*$/.test(schema)) throw new Error('Invalid schema')
  let source = new DatabaseSync(file, { readOnly: true })
  source.exec('PRAGMA trusted_schema = OFF')
  if (snapshotDir) {
    fs.mkdirSync(snapshotDir, { recursive: true, mode: 0o700 })
    const snapshot = path.join(snapshotDir, path.basename(file))
    await backup(source, snapshot)
    source.close(); fs.chmodSync(snapshot, 0o600)
    source = new DatabaseSync(snapshot, { readOnly: true })
  }
  try {
    if (source.prepare('PRAGMA quick_check').get().quick_check !== 'ok') throw new Error('SQLite integrity check failed')
    const dictionary = schema.startsWith('dictionary')
    const names = dictionary ? ['dict'] : source.prepare(
      "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").all().map(t => t.name)
    if (replace && schema !== 'dictionary') throw new Error('Only dictionary replacement is allowed')
    if (replace) await client.query(`DROP SCHEMA IF EXISTS ${quote(schema)} CASCADE`)
    await client.query(`CREATE SCHEMA ${quote(schema)}`)
    await client.query(`SET LOCAL search_path TO ${quote(schema)}, public`)
    const report = []
    for (const table of names) {
      const ddl = source.prepare("SELECT sql FROM sqlite_master WHERE type='table' AND name=?").get(table)?.sql
      if (!ddl || /^CREATE VIRTUAL/i.test(ddl)) throw new Error('Unexpected source table')
      const translated = postgresSql(ddl)
        .replace(/INTEGER\s+PRIMARY KEY\s+AUTOINCREMENT/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      await client.query(translated)
      report.push(await copyTable(client, source, table, schema))
      if (/AUTOINCREMENT/i.test(ddl)) {
        await client.query(`SELECT setval(pg_get_serial_sequence('${schema}.${table}', 'id'), coalesce((SELECT max(id) FROM ${quote(table)}), 1), EXISTS(SELECT 1 FROM ${quote(table)}))`)
      }
      console.log(`${schema}.${table}: ${report.at(-1).rows} rows, SHA-256 verified`)
    }
    for (const index of source.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name").all()) {
      if (dictionary && !/\bON\s+dict\b/i.test(index.sql)) continue
      await client.query(index.sql)
    }
    if (dictionary) {
      await client.query(`ALTER TABLE dict ADD COLUMN origin_name_search tsvector GENERATED ALWAYS AS (to_tsvector('simple', origin_name)) STORED,
        ADD COLUMN trans_name_search tsvector GENERATED ALWAYS AS (to_tsvector('simple', trans_name)) STORED`)
      await client.query('CREATE INDEX dict_origin_search_idx ON dict USING gin(origin_name_search)')
      await client.query('CREATE INDEX dict_trans_search_idx ON dict USING gin(trans_name_search)')
      await client.query('CREATE INDEX dict_origin_trigram_idx ON dict USING gin(origin_name gin_trgm_ops)')
      await client.query('CREATE INDEX dict_trans_trigram_idx ON dict USING gin(trans_name gin_trgm_ops)')
      await client.query('ANALYZE dict')
    }
    return report
  } finally { source.close() }
}

async function main() {
  const dictionaryFile = process.argv.includes('--dictionary') ? process.argv[process.argv.indexOf('--dictionary') + 1] : null
  const pool = createPostgresPool(process.env.VMCT_DATABASE_URL)
  const client = await pool.connect()
  const dataDir = process.env.VMCT_DATA_DIR || '/var/lib/vmct-website/data'
  try {
    await client.query('BEGIN')
    await client.query('SET LOCAL statement_timeout = 0')
    await client.query("SELECT pg_advisory_xact_lock(hashtext('vmct-website-migration'))")
    await client.query('CREATE EXTENSION IF NOT EXISTS pg_trgm')
    const report = []
    if (dictionaryFile) {
      report.push(...await importDatabase(client, dictionaryFile, 'dictionary_next'))
      await client.query('COMMIT')
      await client.query('BEGIN')
      await client.query("SELECT pg_advisory_xact_lock(hashtext('vmct-website-migration'))")
      await client.query('SET LOCAL lock_timeout = 10000')
      await client.query('DROP SCHEMA IF EXISTS dictionary_previous CASCADE')
      await client.query('ALTER SCHEMA dictionary RENAME TO dictionary_previous')
      await client.query('ALTER SCHEMA dictionary_next RENAME TO dictionary')
    } else {
      const snapshotDir = path.join(dataDir, '.backups', 'postgres-' + new Date().toISOString().replaceAll(':', '-'))
      for (const [schema, name] of [['content', 'content.sqlite'], ['feedback', 'translation-feedback.sqlite'], ['dictionary', 'dictionary.sqlite']]) {
        report.push(...await importDatabase(client, path.join(dataDir, name), schema, { snapshotDir }))
      }
      fs.writeFileSync(path.join(snapshotDir, 'validation.json'), JSON.stringify(report, null, 2), { mode: 0o600 })
    }
    await client.query('COMMIT')
    console.log('PostgreSQL import committed; source SQLite files retained.')
  } catch (error) {
    await client.query('ROLLBACK')
    console.error('PostgreSQL import rolled back:', error.message)
    process.exitCode = 1
  } finally { client.release(); await pool.end() }
}
